#!/usr/bin/env node
// Gossoko — seed the first 10 venues on free Pro (the "Founding 10": free Pro for
// 90 days in return for putting up the Gossoko QR).
//
// DRY RUN BY DEFAULT. Nothing is written unless --apply is given.
//
//   node scripts/seed-first10-pro.mjs                 # dry run: validate + print the plan
//   node scripts/seed-first10-pro.mjs --sql > out.sql # idempotent SQL for the Supabase SQL editor
//   node scripts/seed-first10-pro.mjs --apply         # write (needs SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY)
//   options: --file <path> (default scripts/data/first10-venues.json)
//            --actor <admin profile uuid>  (adds an audit_logs row per grant; audit_logs.actor_id is NOT NULL)
//
// Idempotent: a venue is matched by slug (created only if missing); a venue that
// already has a Founding-10 plan, a Stripe plan or live Pro time is left alone,
// so running it twice changes nothing. Placeholder rows are refused by --apply/--sql.
// The service-role key is read from the environment only and never printed.

import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const FOUNDING_NOTE = 'founding-10';
export const VENUE_TYPES = ['cafe', 'food_truck', 'bakery', 'servo', 'gossoko_van', 'snack_bar', 'restaurant', 'cafe_and_food_truck'];
const REQUIRED = ['slug', 'name', 'type', 'address', 'suburb', 'state', 'latitude', 'longitude'];

/** Problems with the venue list, as human-readable strings (empty = fine). */
export function validateRows(rows) {
  const errs = [];
  if (!Array.isArray(rows) || rows.length === 0) return ['No venues in the file.'];
  if (rows.length > 10) errs.push(`${rows.length} venues listed; the Founding offer is for 10.`);
  const seen = new Set();
  rows.forEach((r, i) => {
    const at = `venue ${i + 1} (${r?.slug ?? '?'})`;
    for (const k of REQUIRED) if (r?.[k] === undefined || r[k] === '') errs.push(`${at}: missing ${k}`);
    if (r?.slug && !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(r.slug)) errs.push(`${at}: slug must be lower-case-with-dashes`);
    if (r?.slug && seen.has(r.slug)) errs.push(`${at}: duplicate slug`);
    seen.add(r?.slug);
    if (r?.type && !VENUE_TYPES.includes(r.type)) errs.push(`${at}: type must be one of ${VENUE_TYPES.join(', ')}`);
    if (typeof r?.latitude !== 'number' || r.latitude < -44 || r.latitude > -10) errs.push(`${at}: latitude not in Australia`);
    if (typeof r?.longitude !== 'number' || r.longitude < 112 || r.longitude > 154) errs.push(`${at}: longitude not in Australia`);
  });
  return errs;
}

export const placeholders = (rows) => rows.filter((r) => r.placeholder === true).map((r) => r.slug);

/**
 * What would happen to each venue.
 * venues: Map slug → { id, pro_until }   plans: Map venue_id → { status, source, note, current_period_end }
 */
export function planSeed(rows, venues, plans, now = new Date()) {
  return rows.map((r) => {
    const v = venues.get(r.slug);
    if (!v) return { slug: r.slug, name: r.name, action: 'create+grant' };
    const p = plans.get(v.id);
    if (p?.note?.startsWith(FOUNDING_NOTE)) return { slug: r.slug, name: r.name, venueId: v.id, action: 'skip', why: 'already a Founding-10 venue' };
    if (p?.source === 'stripe') return { slug: r.slug, name: r.name, venueId: v.id, action: 'skip', why: 'pays through Stripe' };
    if (v.pro_until && new Date(v.pro_until) > now) return { slug: r.slug, name: r.name, venueId: v.id, action: 'skip', why: 'already has Pro time' };
    return { slug: r.slug, name: r.name, venueId: v.id, action: 'grant' };
  });
}

const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);

/** Idempotent SQL doing the same as --apply (for the SQL editor). */
export function toSql(rows, days, actor = null) {
  const lines = [
    '-- Gossoko Founding 10: free Pro for ' + days + ' days. Generated by scripts/seed-first10-pro.mjs. Safe to run twice.',
    'begin;',
    'set local search_path to gossoko, public, extensions;',
  ];
  for (const r of rows) {
    lines.push(
      `insert into gossoko.venues (slug, name, type, address, suburb, state, postcode, latitude, longitude, moderation_status)`,
      `  select ${q(r.slug)}, ${q(r.name)}, ${q(r.type)}::gossoko.venue_type, ${q(r.address)}, ${q(r.suburb)}, ${q(r.state)}, ${q(r.postcode)}, ${Number(r.latitude)}, ${Number(r.longitude)}, 'approved'`,
      `  where not exists (select 1 from gossoko.venues where slug = ${q(r.slug)} and deleted_at is null);`,
      `insert into gossoko.venue_plans (venue_id, status, current_period_end, source, note)`,
      `  select v.id, 'trial', now() + make_interval(days => ${Number(days)}), 'manual', '${FOUNDING_NOTE}: free Pro for the QR'`,
      `  from gossoko.venues v left join gossoko.venue_plans p on p.venue_id = v.id`,
      `  where v.slug = ${q(r.slug)} and v.deleted_at is null`,
      `    and p.venue_id is null and coalesce(v.pro_until, '-infinity') <= now();`,
    );
    if (actor) {
      lines.push(
        `insert into gossoko.audit_logs (actor_id, action_type, resource_type, resource_id, new_values, reason)`,
        `  select ${q(actor)}::uuid, 'venue.pro_granted', 'venues', v.id, jsonb_build_object('days', ${Number(days)}, 'founding', true), '${FOUNDING_NOTE}'`,
        `  from gossoko.venues v join gossoko.venue_plans p on p.venue_id = v.id`,
        `  where v.slug = ${q(r.slug)} and p.note like '${FOUNDING_NOTE}%' and p.created_at > now() - interval '1 minute'`,
        `    and not exists (select 1 from gossoko.audit_logs a where a.resource_id = v.id and a.reason = '${FOUNDING_NOTE}');`,
      );
    }
  }
  lines.push('commit;');
  return lines.join('\n') + '\n';
}

function arg(argv, name) {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : undefined;
}

async function main(argv) {
  const file = arg(argv, '--file') ?? new URL('./data/first10-venues.json', import.meta.url);
  const doc = JSON.parse(readFileSync(file, 'utf8'));
  const rows = doc.venues ?? [];
  const days = Number(doc.days ?? 90);
  const actor = arg(argv, '--actor') ?? null;
  const apply = argv.includes('--apply');
  const sql = argv.includes('--sql');

  const errs = validateRows(rows);
  if (errs.length) { console.error('Fix the venue list first:\n  ' + errs.join('\n  ')); return 2; }
  const ph = placeholders(rows);
  if ((apply || sql) && ph.length) {
    console.error(`Refusing: ${ph.length} placeholder row(s) (${ph.join(', ')}). Put real venues in ${file} and remove "placeholder": true.`);
    return 3;
  }
  if (sql) { process.stdout.write(toSql(rows, days, actor)); return 0; }

  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  let venues = new Map(); let plans = new Map(); let sb = null;
  if (url && key) {
    const { createClient } = await import('@supabase/supabase-js');
    sb = createClient(url, key, { db: { schema: 'gossoko' }, auth: { persistSession: false } });
    const v = await sb.from('venues').select('id, slug, pro_until').in('slug', rows.map((r) => r.slug)).is('deleted_at', null);
    if (v.error) { console.error('Could not read venues:', v.error.message); return 1; }
    venues = new Map(v.data.map((x) => [x.slug, x]));
    if (venues.size) {
      const p = await sb.from('venue_plans').select('venue_id, status, source, note, current_period_end').in('venue_id', [...venues.values()].map((x) => x.id));
      if (p.error) { console.error('Could not read plans:', p.error.message); return 1; }
      plans = new Map(p.data.map((x) => [x.venue_id, x]));
    }
  } else if (apply) {
    console.error('--apply needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in the environment.');
    return 1;
  }

  const plan = planSeed(rows, venues, plans);
  console.log(`${apply ? 'APPLY' : 'DRY RUN'} — Founding 10, ${days} days free Pro${sb ? '' : ' (no Supabase env: planned against an empty database)'}`);
  for (const p of plan) console.log(`  ${p.action.padEnd(12)} ${p.slug}${p.why ? `  (${p.why})` : ''}`);
  if (ph.length) console.log(`\n${ph.length} placeholder row(s): this list is NOT real yet.`);
  if (!apply) { console.log('\nNothing written. Re-run with --apply to write.'); return 0; }

  const end = new Date(Date.now() + days * 86400000).toISOString();
  for (const p of plan) {
    if (p.action === 'skip') continue;
    let id = p.venueId;
    if (p.action === 'create+grant') {
      const r = rows.find((x) => x.slug === p.slug);
      const ins = await sb.from('venues').insert({
        slug: r.slug, name: r.name, type: r.type, address: r.address, suburb: r.suburb, state: r.state,
        postcode: r.postcode ?? null, latitude: r.latitude, longitude: r.longitude, moderation_status: 'approved',
      }).select('id').single();
      if (ins.error) { console.error(`  ${p.slug}: venue insert failed: ${ins.error.message}`); continue; }
      id = ins.data.id;
    }
    const g = await sb.from('venue_plans').upsert({
      venue_id: id, status: 'trial', current_period_end: end, source: 'manual', note: `${FOUNDING_NOTE}: free Pro for the QR`,
    }, { onConflict: 'venue_id' });
    if (g.error) { console.error(`  ${p.slug}: grant failed: ${g.error.message}`); continue; }
    if (actor) {
      await sb.from('audit_logs').insert({ actor_id: actor, action_type: 'venue.pro_granted', resource_type: 'venues', resource_id: id,
        new_values: { days, until: end, founding: true }, reason: FOUNDING_NOTE });
    }
    console.log(`  done         ${p.slug} → Pro until ${end.slice(0, 10)}`);
  }
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).then((c) => process.exit(c), (e) => { console.error(e?.message ?? e); process.exit(1); });
}
